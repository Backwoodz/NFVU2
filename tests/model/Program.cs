using System;
using System.IO;
using System.Linq;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;
using Rachel350Z;

class Program {
    static int checks;
    static void Check(bool valid,string name) {
        if(!valid)throw new Exception(name);
        Console.WriteLine("PASS "+name);checks++;
    }
    static void ExpectInvalid<T>(string name, string json) where T:Exception {
        string path=Path.Combine(AppContext.BaseDirectory,name+".json");
        File.WriteAllText(path,json);
        try { ModelFile.Load(path); }
        catch(T) { Console.WriteLine("PASS rejected "+name);checks++;return; }
        throw new Exception("Unexpectedly accepted "+name);
    }
    static void Main(string[] args) {
        var model=ModelFile.Load(args[0]);
        Check(model.schemaVersion==2 && model.preset=="DDAY_PLAYER_CAR","original beginning-of-game preset");
        Check(model.parts.Any(p=>p.name.StartsWith("350Z_KITW02_BODY_A")) && model.parts.Any(p=>p.name.StartsWith("SPOILER_STYLE02_A")),"widebody and spoiler imported");
        Check(model.parts.Any(p=>p.group=="wheel") && model.parts.Any(p=>p.group=="brake"),"original rim and brake geometry");
        var tyre=model.parts.Single(p=>p.group=="wheel" && model.materials[p.material].name.StartsWith("78743ca1_"));
        double tyreRadius=tyre.indices.Select(i=>tyre.vertices[i]).Max(v=>Math.Sqrt(v.y*v.y+v.z*v.z));
        Check(Math.Abs(tyreRadius-.35)<.00001,"visible tyre is 70 cm across, excluding backing geometry");
        var tyreVertices=tyre.indices.Select(i=>tyre.vertices[i]).ToArray();
        Check(Math.Abs(tyreVertices.Max(v=>v.x)-tyreVertices.Min(v=>v.x)-.28)<.00001,"widebody tyre tread is 28 cm wide");
        var sportRotor=model.parts.Single(p=>p.group=="brake" && model.materials[p.material].name.StartsWith("b1aae6bb_"));
        double rotorRadius=sportRotor.indices.Select(i=>sportRotor.vertices[i]).Max(v=>Math.Sqrt(v.y*v.y+v.z*v.z));
        Check(sportRotor.name.StartsWith("BRAKE_STYLE03") && Math.Abs(rotorRadius-.19)<.00001,"sport brake rotor has 38 cm diameter");
        Check(sportRotor.rotatesWithWheel && model.parts.Where(p=>p.group=="brake"&&p!=sportRotor).All(p=>!p.rotatesWithWheel),"brake rotor spins with the wheel while calipers stay fixed");
        Check(model.textures.Any(t=>t.name=="rachel_paint" && t.width==512 && t.height==512),"original vinyl atlas present");
        Check(model.parts.All(p=>p.normals.Length==p.vertices.Length && p.uv.Length==p.vertices.Length),"authored UVs and normals retained");
        Check(model.lights.Count(l=>l.role=="headlight")==2 && model.lights.Count(l=>l.role=="taillight")==2 && model.lights.Count(l=>l.role=="plate")==1,"front rear and plate light locators");
        Check(model.parts.Count(p=>p.lightRole=="headlight")==2 && model.parts.Count(p=>p.lightRole=="taillight")==2,"emission restricted to actual lamp surfaces");
        Check(model.lights.Count(l=>l.role=="reverse")==2 && model.parts.Count(p=>p.lightRole=="reverse")==2,"two bumper reverse lamp surfaces and projectors");
        Check(model.parts.Where(p=>p.lightRole=="reverse").All(p=>p.indices.All(i=>p.vertices[i].z < -1.5f)),"white reverse emission is confined to the rear bumper");
        var plate=model.parts.Single(p=>p.name=="NFVU2_license_plate_rectangle");
        Check(plate.indices.Length==6 && plate.vertices.All(v=>v.z < -2f) && model.textures[model.materials[plate.material].texture].name=="original_license_plate","original plate texture mounted on rear rectangle");
        Check(model.neonTexture>=0 && model.textures[model.neonTexture].name=="350Z_NEON","original vehicle-specific neon mask");
        Check(model.effectEmitters.Count(e=>e.role=="exhaust")==4 && model.effectEmitters.Count(e=>e.role=="purge")==4,"four exhaust mouths and four purge jets exported");
        Check(model.effectEmitters.Where(e=>e.role=="exhaust").All(e=>e.position.z < -1.9f && e.direction.z < -.9f),"exhaust flames originate behind car and point rearward");
        Check(model.nitroFlameTexture>=0 && model.nitroPurgeTexture>=0 && model.textures[model.nitroFlameTexture].width==128 && model.textures[model.nitroPurgeTexture].width==128,"original nitrous particle atlases present");
        Check(model.materials.Any(m=>m.name.StartsWith("wheel_chrome_")) && model.materials.Any(m=>m.name.StartsWith("wheel_gold_")),"chrome lip and gold star use separate materials");
        Console.WriteLine("PASS model: "+model.parts.Length+" slices, "+model.parts.Sum(p=>p.indices.Length/3)+" triangles");checks++;
        ExpectInvalid<InvalidDataException>("missing-parts","{}");
        ExpectInvalid<InvalidDataException>("empty-file","");
        ExpectInvalid<JsonException>("truncated-json","{\"parts\":[");
        var doc=JObject.Parse(File.ReadAllText(args[0]));
        doc["parts"][0]["indices"][0]=-1;
        ExpectInvalid<InvalidDataException>("negative-index",doc.ToString(Formatting.None));
        doc["parts"][0]["indices"][0]=999999;
        ExpectInvalid<InvalidDataException>("oversized-index",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));
        doc["parts"][0]["vertices"][0]["x"]=1000;
        ExpectInvalid<InvalidDataException>("invalid-coordinate",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["parts"][0]["material"]=999;
        ExpectInvalid<InvalidDataException>("invalid-material-index",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["parts"][0]["uv"]=new JArray();
        ExpectInvalid<InvalidDataException>("missing-uvs",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["textures"][0]["width"]=2049;
        ExpectInvalid<InvalidDataException>("oversized-texture",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["textures"][0]["rgba"]="AA==";
        ExpectInvalid<InvalidDataException>("truncated-texture",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["materials"][0]["texture"]=999;
        ExpectInvalid<InvalidDataException>("invalid-texture-index",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["frontWheelVisualOffset"]=10;
        ExpectInvalid<InvalidDataException>("invalid-visual-wheel-offset",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["neonTexture"]=999;
        ExpectInvalid<InvalidDataException>("invalid-neon-texture",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["lights"][0]["direction"]=JObject.Parse("{x:0,y:0,z:0}");
        ExpectInvalid<InvalidDataException>("zero-light-direction",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["lights"][0]["role"]="unknown";
        ExpectInvalid<InvalidDataException>("invalid-light-role",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["parts"][0]["lightRole"]="unknown";
        ExpectInvalid<InvalidDataException>("invalid-emission-role",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["parts"][0]["rotatesWithWheel"]=true;
        ExpectInvalid<InvalidDataException>("rotating-body-part",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["nitroFlameTexture"]=999;
        ExpectInvalid<InvalidDataException>("invalid-nitro-texture",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["effectEmitters"][0]["direction"]=JObject.Parse("{x:0,y:0,z:0}");
        ExpectInvalid<InvalidDataException>("zero-effect-direction",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc["effectEmitters"][0]["role"]="unknown";
        ExpectInvalid<InvalidDataException>("invalid-effect-role",doc.ToString(Formatting.None));
        doc=JObject.Parse(File.ReadAllText(args[0]));doc.Remove("lights");doc.Remove("neonTexture");
        doc.Remove("effectEmitters");doc.Remove("nitroFlameTexture");doc.Remove("nitroPurgeTexture");
        foreach(var part in doc["parts"]) ((JObject)part).Remove("lightRole");
        string legacyPath=Path.Combine(AppContext.BaseDirectory,"legacy-visual-model.json");File.WriteAllText(legacyPath,doc.ToString(Formatting.None));
        var legacy=ModelFile.Load(legacyPath);
        Check(legacy.lights==null && legacy.neonTexture==-1 && legacy.effectEmitters==null && legacy.nitroFlameTexture==-1 && legacy.nitroPurgeTexture==-1,"existing schema-2 models remain loadable without effects metadata");
        var lamps=new VehicleLightingState();lamps.Update(false,false);
        Check(!lamps.Enabled && !lamps.RearLightsOn,"spawned empty vehicle starts with lights off");
        lamps.Update(true,false);Check(lamps.Enabled && lamps.RearLightsOn,"entry automatically enables front and rear lighting");
        lamps.Enabled=false;lamps.Update(true,false);
        Check(!lamps.Enabled && !lamps.RearLightsOn,"manual off persists throughout the same drive");
        lamps.Update(true,true);Check(!lamps.Enabled && lamps.BrakeLightsOn && lamps.RearLightsOn,"braking remains visible with main lights off");
        lamps.Update(false,true);Check(!lamps.Enabled && !lamps.BrakeLightsOn && !lamps.RearLightsOn,"exit releases lighting and brake state");
        lamps.Update(true,false);Check(lamps.Enabled,"a subsequent entry enables the lights again");
        lamps.Update(true,true,5,-1);
        Check(!lamps.ReverseLightsOn,"S braking forward motion does not illuminate reverse lamps");
        lamps.Enabled=false;lamps.Update(true,false,0,-1);
        Check(lamps.ReverseLightsOn && !lamps.Enabled,"reverse selection illuminates white lamps with main lights off");
        lamps.Update(true,false,-3,0);
        Check(lamps.ReverseLightsOn,"coasting in reverse keeps the reverse lamps lit");
        lamps.Update(true,true,-3,1);
        Check(lamps.ReverseLightsOn && lamps.BrakeLightsOn,"braking while reversing retains reverse and brake lamps");
        lamps.Update(true,false,0,1);
        Check(!lamps.ReverseLightsOn,"selecting forward drive switches reverse lamps off");
        lamps.Update(true,false,-1,0);
        Check(!lamps.ReverseLightsOn,"rolling backwards without reverse selection does not light reverse lamps");
        lamps.Update(true,false,0,-1);lamps.Update(false,false,-1,-1);
        Check(!lamps.ReverseLightsOn,"exit clears reverse selection");
        lamps.Update(true,false,0,-1);lamps.Update(true,false,float.NaN,-1);
        Check(!lamps.ReverseLightsOn,"invalid velocity cannot leave reverse lamps on");
        lamps.Update(true,true,.651f,-1);
        Check(!lamps.ReverseLightsOn,"reverse does not select above handling speed threshold");
        lamps.Update(true,true,.65f,-1);
        Check(lamps.ReverseLightsOn,"reverse selects at exact handling threshold even with brake held");
        lamps.Update(true,false,1,0);
        Check(lamps.ReverseLightsOn,"slope rollback does not silently change selected reverse gear");
        lamps.Update(true,true,-.651f,1);
        Check(lamps.ReverseLightsOn,"forward input still brakes below the negative handling threshold");
        lamps.Update(true,false,-.65f,1);
        Check(!lamps.ReverseLightsOn,"forward selects at exact negative handling threshold");
        Check(DrivingMath.DirectionBrake(10,-1) && DrivingMath.TorqueFactor(10,-1,true)==0,"reverse input brakes forward motion");
        Check(DrivingMath.DirectionBrake(-5,1) && DrivingMath.TorqueFactor(-5,1,true)==0,"forward input brakes reverse motion");
        Check(!DrivingMath.DirectionBrake(0,-1) && DrivingMath.TorqueFactor(0,-1,true)==1,"reverse engages at standstill");
        Check(DrivingMath.TorqueFactor(20,1,true)==0 && DrivingMath.TorqueFactor(-8,-1,true)==0,"terrain and reverse speed limits");
        Check(DrivingMath.SteeringLimit(25,true)<DrivingMath.SteeringLimit(0,true) && DrivingMath.SteeringLimit(-25,true)==DrivingMath.SteeringLimit(25,true),"steering reduced with speed in either direction");
        float[] terrainWeights=Enumerable.Range(0,4).Select(i=>DrivingMath.WheelWeight(i,true)).ToArray();
        Check(Math.Abs(terrainWeights.Sum()-1f)<.00001f && terrainWeights[0]>0,"terrain assistance uses all four wheels");
        Check(DrivingMath.WheelWeight(0,false)==0 && DrivingMath.WheelWeight(2,false)>0,"road mode preserves rear-wheel drive");
        Check(Math.Abs(Enumerable.Range(0,4).Sum(i=>DrivingMath.WheelWeight(i,false))-1f)<.00001f,"road mode delivers full torque to the rear axle");
        Check(DrivingMath.GripTorqueFactor(3)<DrivingMath.GripTorqueFactor(0) && DrivingMath.GripTorqueFactor(3)>0,"wheelspin reduces torque without cutting it completely");
        Check(DrivingMath.WrapAngle(540)==-180 && DrivingMath.WrapAngle(-540)==-180 && DrivingMath.WrapAngle(361)==1,"camera can rotate repeatedly in both directions");
        Console.WriteLine(checks+" checks passed against the compiled plugin.");
    }
}
